// Bundle src/ into the single file Hermes loads: desktop/plugin.js.
// The three host modules stay external: the app resolves them to its own copies.
// Dev tooling lives in dev/ (not the repo root) so `hermes plugins install` finds no
// package.json and never asks users to install Node deps: the bundle is committed.
import { build } from 'esbuild'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
process.chdir(ROOT)   // paths below are relative to the repo root (esbuild also gets absWorkingDir: its service may start before this line)

export const ALLOWED_IMPORTS = ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime']

const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url)))

export function options(outfile = 'desktop/plugin.js') {
  return {
    absWorkingDir: ROOT,
    entryPoints: ['src/index.jsx'],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: ALLOWED_IMPORTS,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'warning',
    banner: {
      js: `// Officecraft ${pkg.version} — GENERATED by \`npm --prefix dev run build\` from src/. Do not edit by hand.`
    }
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await build(options())
  console.log('built desktop/plugin.js')
}
